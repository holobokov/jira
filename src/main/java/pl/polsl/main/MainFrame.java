    private void fillTable() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        for (Issue issue : issues) {
            model.addRow(new Object[]{
                issue.getId(),
                issue.getIssueKey(),
                issue.getTitle(),
                issue.getPriority(),
                issue.getStatus()
            });
        }
    }

